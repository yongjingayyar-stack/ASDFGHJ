  function filesFor(plan) {
    const f = {};
    Object.assign(f, COMMON(plan));
    const langs = (plan.langs && plan.langs.length) ? plan.langs : [plan.lang || 'js'];
    for (const id of langs) {
      const em = EMITTERS[id];
      if (em) Object.assign(f, em(plan));
    }
    /* the playable web core must exist even if the user deselected it */
    if (!f['js/game.js']) Object.assign(f, EMITTERS.js(plan));
    return f;
  }

  /* primary entry returns full file map for chosen language emphasis */
  function generate(plan, persona) {
    plan.personaDigest = 'sha1:' + (Arc.Planner.hashSeed(persona) >>> 0).toString(16);
    const files = filesFor(plan);
    /* reorder so the requested language leads the tree */
    const wantExt = (Arc.State.LANGS.find(l => l.id === plan.lang) || {}).ext;
    const keys = Object.keys(files).sort((a, b) => {
      const pa = wantExt && a.endsWith(wantExt) ? 0 : 1;
      const pb = wantExt && b.endsWith(wantExt) ? 0 : 1;
      return pa - pb || a.localeCompare(b);
    });
    const ordered = {}; keys.forEach(k => ordered[k] = files[k]);
    return ordered;
  }

  global.Arc = global.Arc || {};
  global.Arc.Generators = { generate, filesFor, EMITTERS };
