  /* ─────────── GLSL post shader ─────────── */
  function genShader(plan) {
    return `// ${plan.title} — crt.glsl · bloom + palette quantise + barrel distortion
// Fragment stage only; expects tDiffuse (linear RGBA), uniform vec2 uRes, float uTime.
precision highp float;

uniform sampler2D tDiffuse;
uniform vec2  uRes;
uniform float uTime;
uniform float uCurvature;   // 0.06 typical CRT
uniform float uScanStrength;// 0.25 typical

const vec3 PAL[4] = vec3[4](
${plan.palette.map(glslvec).map((s, i) => '  ' + s + (i < 3 ? ',' : '')).join('\n')}
);

float hash(vec2 p){ return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453); }

vec2 barrel(vec2 uv, float k){
  vec2 c = uv * 2.0 - 1.0;
  float r2 = dot(c, c);
  return (c * (1.0 + k * r2)) * 0.5 + 0.5;
}

vec3 quantise(vec3 col){
  float best = 1e9; vec3 outc = col;
  for (int i = 0; i < 4; i++){
    float d = distance(col, PAL[i]);
    if (d < best){ best = d; outc = PAL[i]; }
  }
  return mix(col, outc, 0.28);   // keep some fidelity
}

void main(){
  vec2 uv = barrel(gl_FragCoord.xy / uRes, uCurvature);
  if (uv.x < 0.0 || uv.x > 1.0 || uv.y < 0.0 || uv.y > 1.0){
    gl_FragColor = vec4(0.0, 0.0, 0.0, 1.0); return;
  }

  vec3 base = texture2D(tDiffuse, uv).rgb;

  // cheap 5-tap bloom on bright pixels only
  vec3 glow = vec3(0.0);
  for (int i = -2; i <= 2; i++)
    for (int j = -2; j <= 2; j++) {
      vec3 s = texture2D(tDiffuse, uv + vec2(float(i), float(j)) * 2.5 / uRes).rgb;
      glow += max(s - 0.62, 0.0);
    }
  glow /= 25.0;

  // phosphor mask + scanlines
  float line = sin(uv.y * uRes.y * 3.14159) * 0.5 + 0.5;
  vec3 mask = vec3(1.0);
  int slot = int(mod(gl_FragCoord.x, 3.0));
  mask[slot]     *= 1.18;
  mask[(slot + 1) % 3] *= 0.86;

  vec3 col = base + glow * 1.9;
  col *= mix(vec3(1.0), vec3(line), uScanStrength);
  col *= mask;
  col = quantise(col);
  col += (hash(uv * uRes + uTime) - 0.5) * 0.035;      // grain
  col *= smoothstep(1.25, 0.35, length(uv * 2.0 - 1.0)); // vignette

  gl_FragColor = vec4(pow(max(col, 0.0), vec3(0.92)), 1.0);
}`;
  }

