  function genGLSLBloom(plan) {
    return `/* ${plan.title} bloom pre-pass — pairs with shader/crt.glsl */
precision mediump float;
uniform sampler2D uScene;
uniform vec2  uRes;
uniform float uThresh;
varying vec2 vUv;

void main() {
  vec3 src = texture2D(uScene, vUv).rgb;
  float lum = dot(src, vec3(0.2126, 0.7152, 0.0722));
  vec3 glow = src * smoothstep(uThresh, 1.0, lum);
  vec3 acc = vec3(0.0);
  float wsum = 0.0;
  for (int x = -2; x <= 2; x++) {
    for (int y = -2; y <= 2; y++) {
      vec2 off = vec2(float(x), float(y)) / uRes * 2.0;
      vec3 s = texture2D(uScene, vUv + off).rgb;
      float l = dot(s, vec3(0.2126, 0.7152, 0.0722));
      float w = 1.0 - length(off) * uRes.x * 0.002;
      acc += s * max(0.0, l - uThresh) * w;
      wsum += w;
    }
  }
  vec3 bloom = acc / max(wsum, 1.0) * 1.8;
  gl_FragColor = vec4(glow + bloom + src * 0.15, 1.0);
}
`;
  }

